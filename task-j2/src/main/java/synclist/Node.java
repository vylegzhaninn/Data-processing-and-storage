package synclist;

import java.util.concurrent.locks.ReentrantLock;

/**
 * Узел двусвязного списка строк.
 *
 * <p>Значение узла неизменяемо ({@code final}): при сортировке записи
 * переставляются переустановкой ссылок {@link #prev} и {@link #next},
 * а не обменом содержимого строк между узлами.</p>
 *
 * <p>Каждый узел несёт собственный замок {@link ReentrantLock}. Все участники
 * (главная нить, сортировщики, обход итератором) захватывают замки узлов
 * строго в порядке «ближе к голове списка — раньше»; это исключает
 * взаимные блокировки (deadlock) при конкурирующем доступе.</p>
 *
 * <p>Правило видимости: чтение или запись {@link #prev}/{@link #next} узла
 * допускается только под его замком. Исключение — ещё не опубликованный узел
 * (созданный локально и не присоединённый к списку): его поля безопасно
 * заполняет единственная нить-владелец до первой публикации.</p>
 */
final class Node {

    /** Неизменяемое значение записи; у часовых узлов равно {@code null}. */
    final String value;

    /** Предыдущий узел (ближе к голове); изменяется только под замком. */
    Node prev;

    /** Следующий узел (ближе к хвосту); изменяется только под замком. */
    Node next;

    private final ReentrantLock lock = new ReentrantLock();

    Node(String value) {
        this.value = value;
    }

    void lock() {
        lock.lock();
    }

    void unlock() {
        lock.unlock();
    }
}
